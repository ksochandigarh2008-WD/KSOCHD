/**
 * CONTENT COVERAGE AUDIT
 *
 * WHY THIS EXISTS
 * `defaultContent.js` is the whole editable surface of the public site, and the
 * admin panel is the only way to edit it. Twice now an area has shipped with no
 * editor and nobody noticed, because a missing control is invisible: `faqs` was
 * rendered on the homepage and answered by the AI assistant, yet had no field
 * anywhere in /admin. The only way a human found it was by grepping by hand.
 *
 * WHAT IT DOES
 *   1. Walks every leaf path in `defaultContent` (e.g. `faqs[].q`,
 *      `org.social.facebook`, `donationPresets`).
 *   2. Scans `src/pages/admin/**` for the calls that actually write content —
 *      `setContentPath` / `addListItem` / `updateListItem` / `removeListItem` /
 *      `moveListItem` — and records which paths they address.
 *   3. Reports leaves nothing addresses, and paths addressed that do not exist.
 *
 * DELIBERATELY NOT A NAIVE GREP
 * Only files that bind `setContentPath` are scanned for `set(...)`, otherwise the
 * local form setters in LedgerTab and AccountingTab (`set('amount', ...)`,
 * `set('name', ...)`) look like content paths and the report fills with noise.
 * A scanner that cries wolf gets ignored, which is worse than no scanner.
 *
 * COVERAGE RULE
 * Addressing a path covers it and everything beneath it, because the controls
 * replace the value wholesale: `set('about.body', next)` covers the whole array,
 * and `updateListItem('programs', id, { metrics: next })` covers the fields
 * inside each metric. So `programs[].metrics[].label` counts as covered — which
 * is true here, those inputs bind straight to it.
 *
 * `id` fields are excluded from leaves: they are generated by the store, never
 * authored, and no control should edit them.
 */

import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import defaultContent from '../src/data/defaultContent.js'

const SRC = new URL('../src', import.meta.url).pathname
const ADMIN = join(SRC, 'pages', 'admin')

/* ------------------------------------------------------------------ *
 * 1. Leaves of defaultContent
 * ------------------------------------------------------------------ */

const isPlainObject = (v) => v !== null && typeof v === 'object' && !Array.isArray(v)

/** Union of the keys of every object in an array — rows are not all identical. */
const keysOfArray = (arr) => {
  const keys = new Set()
  for (const item of arr) if (isPlainObject(item)) Object.keys(item).forEach((k) => keys.add(k))
  return [...keys]
}

function leavesOf(value, path = '', out = []) {
  if (Array.isArray(value)) {
    const keys = keysOfArray(value)
    if (!keys.length) {
      // Array of primitives (about.body, donationPresets) — replaced wholesale.
      out.push(path)
      return out
    }
    for (const k of keys) {
      if (k === 'id') continue
      leavesOf(value.find((v) => isPlainObject(v) && k in v)?.[k], `${path}[].${k}`, out)
    }
    return out
  }
  if (isPlainObject(value)) {
    for (const [k, v] of Object.entries(value)) {
      if (k === 'id') continue
      leavesOf(v, path ? `${path}.${k}` : k, out)
    }
    return out
  }
  out.push(path)
  return out
}

/* ------------------------------------------------------------------ *
 * 2. What the admin addresses
 * ------------------------------------------------------------------ */

const sourceFiles = []
;(function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) walk(full)
    else if (/\.jsx?$/.test(entry)) sourceFiles.push(full)
  }
})(ADMIN)

/** Top-level keys of the object literal beginning at `open` (a `{`). */
function objectLiteralKeys(text, open) {
  let depth = 0
  let body = ''
  for (let i = open; i < text.length; i++) {
    const ch = text[i]
    if (ch === '{' || ch === '[' || ch === '(') depth++
    if (ch === '}' || ch === ']' || ch === ')') {
      depth--
      if (depth === 0) break
    }
    if (depth >= 1) body += ch
  }
  body = body.slice(1) // drop the opening brace
  const keys = []
  let d = 0
  let cur = ''
  for (const ch of body) {
    if ('{[('.includes(ch)) d++
    if ('}])'.includes(ch)) d--
    if (ch === ',' && d === 0) { keys.push(cur); cur = '' } else cur += ch
  }
  keys.push(cur)
  return keys
    .map((k) => k.trim().split(':')[0].trim().replace(/^['"]|['"]$/g, ''))
    .filter((k) => /^[A-Za-z_$][\w$]*$/.test(k))
}

const addressed = new Set()
const evidence = new Map()
const note = (path, why) => {
  if (!path) return
  addressed.add(path)
  if (!evidence.has(path)) evidence.set(path, why)
}

for (const file of sourceFiles) {
  const text = readFileSync(file, 'utf8')
  const rel = relative(SRC, file)

  // Only variables actually bound to the content setter count as content writes.
  const setters = [...text.matchAll(/const\s+(\w+)\s*=\s*useSite\(\(s\)\s*=>\s*s\.setContentPath\)/g)]
    .map((mm) => mm[1])

  for (const name of setters) {
    // set('a.b', ...)
    for (const mm of text.matchAll(new RegExp(`\\b${name}\\('([^']+)'`, 'g'))) {
      note(mm[1], `${rel} → ${name}('${mm[1]}')`)
    }
    // set(`a.${k}`, ...) — a template addresses the whole subtree it builds into.
    for (const mm of text.matchAll(new RegExp('\\b' + name + '\\(`([^`$]*)\\$\\{', 'g'))) {
      note(mm[1].replace(/\.$/, ''), `${rel} → ${name}(\`${mm[1]}...\`)`)
    }
  }

  // List operations.
  for (const mm of text.matchAll(/\b(?:add|remove|move)ListItem\('([^']+)'/g)) {
    note(mm[1], `${rel} → ${mm[0].split('(')[0]}('${mm[1]}'…)`)
  }
  for (const mm of text.matchAll(/\baddListItem\('([^']+)',\s*\{/g)) {
    const at = mm.index + mm[0].length - 1
    for (const k of objectLiteralKeys(text, at)) note(`${mm[1]}[].${k}`, `${rel} → addListItem('${mm[1]}')`)
  }
  for (const mm of text.matchAll(/\bupdateListItem\('([^']+)',\s*[^,{}]+,\s*\{/g)) {
    const at = mm.index + mm[0].length - 1
    for (const k of objectLiteralKeys(text, at)) note(`${mm[1]}[].${k}`, `${rel} → updateListItem('${mm[1]}', …, { ${k} })`)
  }
  // A whole-list replacement covers every field on it.
  for (const mm of text.matchAll(/\bupdateListItem\('([^']+)',\s*[^,{}]+,\s*\{(\w+)\}/g)) {
    note(`${mm[1]}[].${mm[2]}`, `${rel} → updateListItem('${mm[1]}')`)
  }
}

/* ------------------------------------------------------------------ *
 * 3. Compare
 * ------------------------------------------------------------------ */

const norm = (p) => p.replace(/\[\]/g, '')
const leaves = [...new Set(leavesOf(defaultContent))].sort()
const addressedList = [...addressed].sort()

const isCovered = (leaf) => {
  const l = norm(leaf)
  for (const a of addressedList) {
    const an = norm(a)
    if (l === an || l.startsWith(`${an}.`)) return true
  }
  return false
}

const uncovered = leaves.filter((l) => !isCovered(l))

/** Addressed paths that match nothing in the content — a stale or misspelled control. */
const dangling = addressedList.filter((a) => {
  const an = norm(a)
  return !leaves.some((l) => {
    const ln = norm(l)
    return ln === an || ln.startsWith(`${an}.`)
  })
})

/* ------------------------------------------------------------------ *
 * 4. Report
 * ------------------------------------------------------------------ */

const KNOWN_GAPS = new Set()
const gaps = uncovered.filter((p) => !KNOWN_GAPS.has(p))

console.log('\nContent coverage audit — defaultContent vs the admin panel\n')
console.log(`  leaves in defaultContent : ${leaves.length}`)
console.log(`  paths the admin addresses : ${addressedList.length}`)
console.log(`  covered                   : ${leaves.length - uncovered.length}`)
console.log(`  NOT covered               : ${uncovered.length}${KNOWN_GAPS.size ? ` (${KNOWN_GAPS.size} documented as known)` : ''}`)

if (uncovered.length) {
  console.log('\n  Uncovered leaves:')
  for (const p of uncovered) console.log(`    ${KNOWN_GAPS.has(p) ? '~' : '!'} ${p}`)
}

if (dangling.length) {
  console.log('\n  Addressed but not present in defaultContent:')
  for (const p of dangling) console.log(`    ? ${p}   (${evidence.get(p)})`)
}

if (gaps.length === 0 && dangling.length === 0) {
  console.log('\n  ✅ Every leaf of the public content is reachable from the admin panel.\n')
  process.exit(0)
}

console.log(
  gaps.length
    ? `\n  ❌ ${gaps.length} leaf/leaves have no editor. Add a control, or record it in KNOWN_GAPS with a reason.\n`
    : '\n  ❌ Addressed paths do not match the content.\n',
)
process.exit(1)
